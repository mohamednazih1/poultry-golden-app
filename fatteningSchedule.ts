export function getGuidelineForDay(day: number): DailyGuideline {
  // Find largest day less than or equal to current day
  const sorted = [...FATTENING_MILESTONES].sort((a, b) => b.day - a.day);
  const matched = sorted.find(m => day >= m.day);
  if (matched) {
    return {
      ...matched,
      day: day // return with the exact requested day
    };
  }
  return FATTENING_MILESTONES[0];
}
